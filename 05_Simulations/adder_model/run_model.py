from .mod_sumador import main as exec_sim
from .pp_functions import bits_to_float
from .sim_monitor import SimMonitor
import argparse
import sys
import os


def parse_arguments():
    parser = argparse.ArgumentParser(
        usage="Run the simulation of a 4 operand FP16 adder",
        description="Bit-accurate simulation of a 4-operand FP16 adder."
    )

    parser.add_argument(
        "-i", "--input_file",
        required=False,
        help="Path to the hex input file generated by the automation script. The file must contain lines of 16 hex encoded values representing 4 FP16 operands. If a file is not provided the script will query the user for 4 operands via terminal"
    )

    parser.add_argument(
        "-o", "--output_file",
        required=False,
        help="Path to dump the expected outputs for the TB."
    )

    parser.add_argument(
        "--gen_assert_signals",
        action="store_true",
        help="Flag to save the expected internal signals to a file."
    )

    parser.add_argument(
        "-d", "--debug", 
        action="store_true",
        default=False,
        help="Print to terminal internal signals."
    )

    return parser.parse_args()

def adder_model(inp_file=None):

    if inp_file is "error_vectors.txt":
        args = argparse.Namespace(
            input_file=inp_file,
            output_file=None,
            gen_assert_signals=False,
            debug=True,
        )
    elif inp_file is not None:
        args = argparse.Namespace(
            input_file=inp_file,
            output_file=None,
            gen_assert_signals=True,
            debug=False,
        )
    else:
        args = parse_arguments()

    debug_en = getattr(args, "debug", False)
    assert_en = getattr(args, "gen_assert_signals", False)

    monitor = SimMonitor(assert_en)

    if (args.input_file or inp_file): # Multiple inputs -> Multiple simulations
        file_path = args.input_file if inp_file is None else inp_file
        try:
            with open(file_path, 'r') as f:
                # each line contains 64 bits of data -> 4 FP16 operands
                lines = f.readlines()
        except FileNotFoundError:
            print(f"ERROR: Could not find input file @ {file_path}")
            exit(1)

        # Silence only the extra debug chatter while preserving later bench output.
        if not debug_en:
            original_stdout = sys.stdout
            devnull = open(os.devnull, 'w')
            try:
                sys.stdout = devnull
                for line in lines:
                    # remove whitespaces and EOL characters
                    clean_line = line.strip()

                    assert(clean_line) # line isn't empty

                    operands_bits = list(int(clean_line[i: i+4], 16) for i in range(0, 16, 4))

                    num1 = bits_to_float(operands_bits[0])
                    num2 = bits_to_float(operands_bits[1])
                    num3 = bits_to_float(operands_bits[2])
                    num4 = bits_to_float(operands_bits[3])

                    exec_sim(num1, num2, num3, num4, monitor)
            finally:
                sys.stdout = original_stdout
                devnull.close()
        else:
            for line in lines:
                # remove whitespaces and EOL characters
                clean_line = line.strip()

                assert(clean_line) # line isn't empty

                operands_bits = list(int(clean_line[i: i+4], 16) for i in range(0, 16, 4))

                num1 = bits_to_float(operands_bits[0])
                num2 = bits_to_float(operands_bits[1])
                num3 = bits_to_float(operands_bits[2])
                num4 = bits_to_float(operands_bits[3])

                exec_sim(num1, num2, num3, num4, monitor)

    else:
        # single input -> single simulation
        # no silencing of prints
        print("-"*50+"\n")
        num1 = float(input("Ingrese el primer número flotante: "))
        num2 = float(input("Ingrese el segundo número flotante: "))
        num3 = float(input("Ingrese el tercer número flotante: "))
        num4 = float(input("Ingrese el cuarto número flotante: "))

        exec_sim(num1, num2, num3, num4, monitor)


    monitor.write_data()



if __name__ == "__main__":   adder_model()
