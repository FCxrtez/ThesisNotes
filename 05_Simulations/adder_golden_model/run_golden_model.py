import numpy as np
import argparse
import sys
from pathlib import Path

try:
    from .adder_frame import AdderFrame
except ImportError:
    from adder_frame import AdderFrame

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from adder_model.pp_functions import bits_to_float

def parse_arguments():
    parser = argparse.ArgumentParser(
        usage="give the four arguments by terminal or provide an input file containing the data in hex format",
        description="Generate the golden reference for a 4 operand FP16 adder"
    )

    parser.add_argument(
        "-i", "--input_file",
        required=False,
        help="Path to the hex input file generated by the automation script. The file must contain lines of 16 hex encoded values representing 4 FP16 operands. If a file is not provided the script will query the user for 4 operands via terminal"
    )

    return parser.parse_args()

def adder_golden_model(Input_file=None):
    args = parse_arguments()

    fp16_adder = AdderFrame("fp16_ref.txt", intermediate_dtype=np.float16)
    fp32_adder = AdderFrame("fp32_ref.txt", intermediate_dtype=np.float32)
    fp64_adder = AdderFrame("fp64_ref.txt", intermediate_dtype=np.float64)

    if (args.input_file or Input_file): # Multiple inputs -> Multiple simulations
        file_path = args.input_file if Input_file is None else Input_file
        try:
            with open(file_path, 'r') as f:
                # each line contains 64 bits of data -> 4 FP16 operands
                lines = f.readlines()
        except FileNotFoundError:
            print(f"ERROR: Could not find input file @ {file_path}")
            exit(1)

        for line in lines:
            # remove whitespaces and EOL characters
            clean_line = line.strip()

            assert(clean_line) # line isn't empty

            operands_bits = list(int(clean_line[i: i+4], 16) for i in range(0, 16, 4))

            num1 = bits_to_float(operands_bits[0])
            num2 = bits_to_float(operands_bits[1])
            num3 = bits_to_float(operands_bits[2])
            num4 = bits_to_float(operands_bits[3])

            fp16_adder.exec_fused_sum(num1, num2, num3, num4)
            fp32_adder.exec_fused_sum(num1, num2, num3, num4)
            fp64_adder.exec_fused_sum(num1, num2, num3, num4)

    else:

        print("-"*50+"\n")
        num1 = float(input("Ingrese el primer número flotante: "))
        num2 = float(input("Ingrese el segundo número flotante: "))
        num3 = float(input("Ingrese el tercer número flotante: "))
        num4 = float(input("Ingrese el cuarto número flotante: "))

        fp16_adder.exec_fused_sum(num1, num2, num3, num4)
        fp32_adder.exec_fused_sum(num1, num2, num3, num4)
        fp64_adder.exec_fused_sum(num1, num2, num3, num4)
    

    fp16_adder.write_to_file()
    fp32_adder.write_to_file()
    fp64_adder.write_to_file()

if __name__ == "__main__":
    adder_golden_model()